"""Embed the built webwarden zipapp into a datz.py single-file deliverable."""

from __future__ import annotations

import argparse
import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
START = "# >>> DATZ PAYLOAD (generated by the packaging step; do not edit) >>>"
END = "# <<< DATZ PAYLOAD <<<"


def build(engine: Path, template: Path, out: Path) -> int:
    if not engine.is_file():
        print(f"missing {engine.name}; build the zipapp first", file=sys.stderr)
        return 1
    blob = engine.read_bytes()
    digest = hashlib.sha256(blob).hexdigest()
    encoded = base64.b64encode(blob).decode("ascii")
    lines = [encoded[i:i + 120] for i in range(0, len(encoded), 120)]
    block = (
        START + "\n"
        f'PAYLOAD_SHA256 = "{digest}"\n'
        'PAYLOAD_B64 = (\n'
        + "".join(f'    "{line}"\n' for line in lines)
        + ")\n"
        + END
    )
    source = template.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(source):
        print(f"payload markers not found in {template.name}", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(pattern.sub(lambda _m: block, source, count=1),
                   encoding="utf-8", newline="\n")
    print(f"embedded {len(blob)} bytes (sha256 {digest[:12]}…) -> "
          f"{out} is now {out.stat().st_size / 1024:.0f} KiB")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", default=str(ROOT / "webwarden.pyz"),
                        help="zipapp to embed (default: webwarden.pyz)")
    parser.add_argument("--template", default=str(ROOT / "datz.py"),
                        help="datz.py source with the payload markers")
    parser.add_argument("--out", default=str(ROOT / "datz.py"),
                        help="destination file (default: rewrite the template)")
    args = parser.parse_args(argv)
    return build(Path(args.engine), Path(args.template), Path(args.out))


if __name__ == "__main__":
    raise SystemExit(main())
